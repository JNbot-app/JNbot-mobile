export function resolveMinecraftVersion(version?: string): '1.21' | '1.18' | '1.16' | '1.8' {
  if (!version) return '1.21';
  const match = version.match(/^1\.(\d+)/);
  if (!match) return '1.21';
  const minor = parseInt(match[1], 10);
  if (minor >= 21) return '1.21';
  if (minor >= 18) return '1.18';
  if (minor >= 16) return '1.16';
  return '1.8';
}

